#!/bin/sh
# gen-openapi-nodejs.sh — generate the nodejs (TypeScript) client for one OpenAPI
# contract, per ADR 0001: openapi-typescript emits the types and openapi-fetch is
# the runtime the generated client depends on. No ephemeral DB needed — the
# contract file is consumed directly.
#
# Usage: scripts/gen-openapi-nodejs.sh --service NAME --version vX.Y.Z
#
# Input : openapi/<service>/openapi.yaml   (hand-authored source of truth)
# Output: openapi/<service>/<version>/nodejs/
#           schema.ts        — openapi-typescript type output
#           index.ts         — typed re-exports + createClient() helper
#           package.json     — @experiencequality/<service>-client @ <version minus v>
#           tsconfig.json    — `npm run typecheck` (tsc --noEmit)
#           .gitignore       — node_modules/, package-lock.json (install-time only)
#
# Tool versions come from pipeline/nodejs/package.json (installed via the
# committed package-lock.json) so regeneration is deterministic.
set -eu

usage() {
  echo "usage: $0 --service NAME --version vX.Y.Z" >&2
  exit 2
}

SERVICE=
VERSION=
while [ $# -gt 0 ]; do
  case "$1" in
    --service) SERVICE=${2:?missing value for --service}; shift 2 ;;
    --version) VERSION=${2:?missing value for --version}; shift 2 ;;
    *) usage ;;
  esac
done
[ -n "$SERVICE" ] && [ -n "$VERSION" ] || usage

# Service names are lowercase kebab-case (docs/contracts-conventions.md).
case "$SERVICE" in
  *[!a-z0-9-]*)
    echo "error: --service must be lowercase kebab-case, got '$SERVICE'" >&2
    exit 2
    ;;
esac

# Version dirs are v-prefixed semver: vX.Y.Z with optional -pre/+build.
if ! printf '%s' "$VERSION" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?(\+[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?$'; then
  echo "error: --version must be v-prefixed semver (e.g. v1.0.0), got '$VERSION'" >&2
  exit 2
fi
PKG_VERSION=${VERSION#v}

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
ROOT_DIR=$(CDPATH='' cd -- "$SCRIPT_DIR/.." && pwd)
PIPELINE_DIR="$ROOT_DIR/pipeline/nodejs"
GEN_BIN="$PIPELINE_DIR/node_modules/.bin/openapi-typescript"

SPEC="$ROOT_DIR/openapi/$SERVICE/openapi.yaml"
if [ ! -f "$SPEC" ]; then
  echo "error: contract not found: $SPEC" >&2
  exit 1
fi

# contracts-conventions.md: <version> must equal info.version plus the v prefix.
SPEC_VERSION=$(awk '
  /^info:[[:space:]]*$/ { ininfo = 1; next }
  /^[^[:space:]#]/      { ininfo = 0 }
  ininfo && $1 == "version:" { v = $2; gsub(/"/, "", v); print v; exit }
' "$SPEC")
if [ "$SPEC_VERSION" != "$PKG_VERSION" ]; then
  echo "error: info.version in $SPEC is '$SPEC_VERSION', expected '$PKG_VERSION'" >&2
  exit 1
fi

if [ ! -x "$GEN_BIN" ]; then
  echo "installing pinned pipeline toolchain (npm ci) ..." >&2
  npm --prefix "$PIPELINE_DIR" ci --no-audit --no-fund
fi

OPENAPI_FETCH_VERSION=$(node -p "require('$PIPELINE_DIR/package.json').devDependencies['openapi-fetch']")
TYPESCRIPT_VERSION=$(node -p "require('$PIPELINE_DIR/package.json').devDependencies['typescript']")

OUT_DIR="$ROOT_DIR/openapi/$SERVICE/$VERSION/nodejs"
mkdir -p "$OUT_DIR"
rm -f "$OUT_DIR/.gitkeep"

"$GEN_BIN" "$SPEC" -o "$OUT_DIR/schema.ts"

cat > "$OUT_DIR/package.json" <<EOF
{
  "name": "@experiencequality/$SERVICE-client",
  "version": "$PKG_VERSION",
  "description": "Generated TypeScript client for the $SERVICE service (openapi/$SERVICE/openapi.yaml, contract $VERSION). Do not edit by hand.",
  "type": "module",
  "main": "./index.ts",
  "types": "./index.ts",
  "exports": {
    ".": "./index.ts"
  },
  "files": [
    "index.ts",
    "schema.ts"
  ],
  "scripts": {
    "typecheck": "tsc --noEmit"
  },
  "dependencies": {
    "openapi-fetch": "$OPENAPI_FETCH_VERSION"
  },
  "devDependencies": {
    "typescript": "$TYPESCRIPT_VERSION"
  },
  "publishConfig": {
    "registry": "https://npm.pkg.github.com"
  }
}
EOF

cat > "$OUT_DIR/index.ts" <<'EOF'
// Generated by scripts/gen-openapi-nodejs.sh — do not edit by hand.
// Fix the contract (openapi.yaml) or the generator, then regenerate.
import createFetchClient, { type ClientOptions } from "openapi-fetch";

import type { components, operations, paths } from "./schema.js";

export type { components, operations, paths };

/**
 * Create a typed client for this service.
 *
 * @param baseUrl Base URL the service is reachable at, e.g. "https://api.example.com".
 * @param options Additional openapi-fetch options (custom fetch, headers, middleware).
 */
export function createClient(
  baseUrl: string,
  options: Omit<ClientOptions, "baseUrl"> = {},
) {
  return createFetchClient<paths>({ ...options, baseUrl });
}

export type Client = ReturnType<typeof createClient>;

export default createClient;
EOF

cat > "$OUT_DIR/tsconfig.json" <<'EOF'
{
  "compilerOptions": {
    "target": "ES2022",
    "lib": ["ES2022", "DOM", "DOM.Iterable"],
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "strict": true,
    "noEmit": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true,
    "verbatimModuleSyntax": true
  },
  "include": ["index.ts", "schema.ts"]
}
EOF

cat > "$OUT_DIR/.gitignore" <<'EOF'
# Install-time artifacts only; the committed client is the .ts output itself.
node_modules/
package-lock.json
EOF

echo "generated $OUT_DIR"
