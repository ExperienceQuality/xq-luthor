#!/bin/sh
# gen-openapi-nodejs.sh — generate the nodejs (TypeScript) client for one OpenAPI
# contract.
#
#   * semver < 1.2.0  → ADR 0001: openapi-typescript + openapi-fetch (legacy)
#   * semver >= 1.2.0 → ADR 0002: @hey-api/openapi-ts (flat SDK + Fetch client)
#
# Usage: scripts/gen-openapi-nodejs.sh --service NAME --version vX.Y.Z
#
# Input : openapi/<service>/openapi.yaml   (hand-authored source of truth)
# Output: openapi/<service>/<version>/nodejs/
#
# Tool versions come from pipeline/nodejs (committed package-lock.json).
set -eu

usage() {
  echo "usage: $0 --service NAME --version vX.Y.Z" >&2
  exit 2
}

SERVICE=
VERSION=
while [ $# -gt 0 ]; do
  case "$1" in
    --service) SERVICE=${2:?missing value for --service}; shift 2 ;;
    --version) VERSION=${2:?missing value for --version}; shift 2 ;;
    *) usage ;;
  esac
done
[ -n "$SERVICE" ] && [ -n "$VERSION" ] || usage

case "$SERVICE" in
  *[!a-z0-9-]*)
    echo "error: --service must be lowercase kebab-case, got '$SERVICE'" >&2
    exit 2
    ;;
esac

if ! printf '%s' "$VERSION" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?(\+[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?$'; then
  echo "error: --version must be v-prefixed semver (e.g. v1.0.0), got '$VERSION'" >&2
  exit 2
fi
PKG_VERSION=${VERSION#v}

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
ROOT_DIR=$(CDPATH='' cd -- "$SCRIPT_DIR/.." && pwd)
PIPELINE_DIR="$ROOT_DIR/pipeline/nodejs"
HEY_API_MIN="1.2.0"

SPEC="$ROOT_DIR/openapi/$SERVICE/openapi.yaml"
if [ ! -f "$SPEC" ]; then
  echo "error: contract not found: $SPEC" >&2
  exit 1
fi

SPEC_VERSION=$(awk '
  /^info:[[:space:]]*$/ { ininfo = 1; next }
  /^[^[:space:]#]/      { ininfo = 0 }
  ininfo && $1 == "version:" { v = $2; gsub(/"/, "", v); print v; exit }
' "$SPEC")
if [ "$SPEC_VERSION" != "$PKG_VERSION" ]; then
  echo "error: info.version in $SPEC is '$SPEC_VERSION', expected '$PKG_VERSION'" >&2
  exit 1
fi

USE_HEY_API=$(node -e "
const v = process.argv[1].split(/[.+]/).slice(0,3).map(Number);
const t = process.argv[2].split('.').map(Number);
const gte = v[0] > t[0] || (v[0] === t[0] && (v[1] > t[1] || (v[1] === t[1] && v[2] >= t[2])));
process.exit(gte ? 0 : 1);
" "$PKG_VERSION" "$HEY_API_MIN" && echo 1 || echo 0)

if [ ! -d "$PIPELINE_DIR/node_modules" ]; then
  echo "installing pinned pipeline toolchain (npm ci) ..." >&2
  npm --prefix "$PIPELINE_DIR" ci --no-audit --no-fund
fi

OUT_DIR="$ROOT_DIR/openapi/$SERVICE/$VERSION/nodejs"
mkdir -p "$OUT_DIR"
rm -f "$OUT_DIR/.gitkeep"

generate_legacy() {
  GEN_BIN="$PIPELINE_DIR/node_modules/.bin/openapi-typescript"
  OPENAPI_FETCH_VERSION=$(node -p "require('$PIPELINE_DIR/package.json').devDependencies['openapi-fetch']")
  TYPESCRIPT_VERSION=$(node -p "require('$PIPELINE_DIR/package.json').devDependencies['typescript']")

  rm -rf "$OUT_DIR/src" "$OUT_DIR/dist" "$OUT_DIR/openapi-ts.config.ts"
  "$GEN_BIN" "$SPEC" -o "$OUT_DIR/schema.ts"

  cat > "$OUT_DIR/package.json" <<EOF
{
  "name": "@experiencequality/$SERVICE-client",
  "version": "$PKG_VERSION",
  "description": "Generated TypeScript client for the $SERVICE service (openapi/$SERVICE/openapi.yaml, contract $VERSION). Do not edit by hand.",
  "type": "module",
  "main": "./index.ts",
  "types": "./index.ts",
  "exports": {
    ".": "./index.ts"
  },
  "files": [
    "index.ts",
    "schema.ts"
  ],
  "scripts": {
    "typecheck": "tsc --noEmit"
  },
  "dependencies": {
    "openapi-fetch": "$OPENAPI_FETCH_VERSION"
  },
  "devDependencies": {
    "typescript": "$TYPESCRIPT_VERSION"
  },
  "repository": {
    "type": "git",
    "url": "git+https://github.com/ExperienceQuality/xq-luthor.git",
    "directory": "openapi/$SERVICE/$VERSION/nodejs"
  },
  "publishConfig": {
    "registry": "https://npm.pkg.github.com"
  }
}
EOF

  cat > "$OUT_DIR/index.ts" <<'EOF'
// Generated by scripts/gen-openapi-nodejs.sh — do not edit by hand.
// Fix the contract (openapi.yaml) or the generator, then regenerate.
import createFetchClient, { type ClientOptions } from "openapi-fetch";

import type { components, operations, paths } from "./schema.js";

export type { components, operations, paths };

/**
 * Create a typed client for this service.
 *
 * @param baseUrl Base URL the service is reachable at, e.g. "https://api.example.com".
 * @param options Additional openapi-fetch options (custom fetch, headers, middleware).
 */
export function createClient(
  baseUrl: string,
  options: Omit<ClientOptions, "baseUrl"> = {},
) {
  return createFetchClient<paths>({ ...options, baseUrl });
}

export type Client = ReturnType<typeof createClient>;

export default createClient;
EOF

  cat > "$OUT_DIR/tsconfig.json" <<'EOF'
{
  "compilerOptions": {
    "target": "ES2022",
    "lib": ["ES2022", "DOM", "DOM.Iterable"],
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "strict": true,
    "noEmit": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true,
    "verbatimModuleSyntax": true
  },
  "include": ["index.ts", "schema.ts"]
}
EOF

  cat > "$OUT_DIR/.gitignore" <<'EOF'
# Install-time artifacts only; the committed client is the .ts output itself.
node_modules/
package-lock.json
EOF
}

generate_hey_api() {
  OPENAPI_TS_BIN="$PIPELINE_DIR/node_modules/.bin/openapi-ts"
  TYPESCRIPT_VERSION=$(node -p "require('$PIPELINE_DIR/package.json').devDependencies['typescript']")
  OPENAPI_TS_VERSION=$(node -p "require('$PIPELINE_DIR/package.json').devDependencies['@hey-api/openapi-ts']")

  rm -rf "$OUT_DIR/src" "$OUT_DIR/dist" "$OUT_DIR/schema.ts" "$OUT_DIR/index.ts"
  mkdir -p "$OUT_DIR/src"

  # Paths relative to this config file so regen is machine-independent.
  cat > "$OUT_DIR/openapi-ts.config.ts" <<'EOF'
// Generated by scripts/gen-openapi-nodejs.sh — do not edit by hand.
export default {
  input: "../../openapi.yaml",
  output: "src",
  plugins: [
    "@hey-api/typescript",
    { name: "@hey-api/client-fetch" },
    {
      name: "@hey-api/sdk",
      operations: { strategy: "flat" },
      paramsStructure: "flat",
      client: "@hey-api/client-fetch",
    },
  ],
};
EOF

  (cd "$OUT_DIR" && "$OPENAPI_TS_BIN" -f ./openapi-ts.config.ts)

  cat > "$OUT_DIR/tsconfig.json" <<'EOF'
{
  "compilerOptions": {
    "target": "ES2022",
    "lib": ["ES2022", "DOM", "DOM.Iterable"],
    "module": "ESNext",
    "moduleResolution": "bundler",
    "declaration": true,
    "declarationMap": true,
    "outDir": "dist",
    "rootDir": "src",
    "strict": true,
    "skipLibCheck": true,
    "esModuleInterop": true
  },
  "include": ["src/**/*.ts"]
}
EOF

  "$PIPELINE_DIR/node_modules/.bin/tsc" -p "$OUT_DIR/tsconfig.json"

  cat > "$OUT_DIR/package.json" <<EOF
{
  "name": "@experiencequality/$SERVICE-client",
  "version": "$PKG_VERSION",
  "description": "Generated TypeScript client for the $SERVICE service (openapi/$SERVICE/openapi.yaml, contract $VERSION). Do not edit by hand. Built with @hey-api/openapi-ts per ADR 0002.",
  "type": "module",
  "main": "./dist/index.js",
  "types": "./dist/index.d.ts",
  "exports": {
    ".": {
      "types": "./dist/index.d.ts",
      "import": "./dist/index.js"
    }
  },
  "files": [
    "dist",
    "src",
    "openapi-ts.config.ts"
  ],
  "scripts": {
    "build": "tsc -p tsconfig.json",
    "typecheck": "tsc -p tsconfig.json --noEmit"
  },
  "devDependencies": {
    "@hey-api/openapi-ts": "$OPENAPI_TS_VERSION",
    "typescript": "$TYPESCRIPT_VERSION"
  },
  "repository": {
    "type": "git",
    "url": "git+https://github.com/ExperienceQuality/xq-luthor.git",
    "directory": "openapi/$SERVICE/$VERSION/nodejs"
  },
  "publishConfig": {
    "registry": "https://npm.pkg.github.com"
  },
  "engines": {
    "node": ">=24"
  }
}
EOF

  cat > "$OUT_DIR/.gitignore" <<'EOF'
node_modules/
package-lock.json
EOF
}

if [ "$USE_HEY_API" = 1 ]; then
  generate_hey_api
else
  generate_legacy
fi

echo "generated $OUT_DIR ($([ "$USE_HEY_API" = 1 ] && echo 'hey-api' || echo 'legacy'))"